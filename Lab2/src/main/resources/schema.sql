CREATE TABLE IF NOT EXISTS vacancies (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                         title VARCHAR(160) NOT NULL,

                                         description TEXT NOT NULL,

                                         requirements TEXT NOT NULL,

                                         salary NUMERIC(12, 2),

                                         employment_type VARCHAR(30) NOT NULL
                                             CHECK (employment_type IN (
                                                                        'FULL_TIME',
                                                                        'PART_TIME',
                                                                        'REMOTE',
                                                                        'PROJECT'
                                                 )),

                                         created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                         applications_count INTEGER NOT NULL DEFAULT 0
                                             CHECK (applications_count >= 0),

                                         CONSTRAINT chk_vacancy_salary
                                             CHECK (salary IS NULL OR salary >= 0)
);


CREATE TABLE IF NOT EXISTS candidates (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                          full_name VARCHAR(160) NOT NULL,

                                          email VARCHAR(190) NOT NULL UNIQUE,

                                          skills TEXT NOT NULL,

                                          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS applications (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                            vacancy_id BIGINT NOT NULL
                                                REFERENCES vacancies(id) ON DELETE CASCADE,

                                            candidate_id BIGINT NOT NULL
                                                REFERENCES candidates(id) ON DELETE CASCADE,

                                            cover_letter TEXT NOT NULL DEFAULT '',

                                            status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
                                                CHECK (status IN (
                                                                  'PENDING',
                                                                  'REVIEWED',
                                                                  'ACCEPTED',
                                                                  'REJECTED'
                                                    )),

                                            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                            CONSTRAINT uq_candidate_vacancy
                                                UNIQUE (candidate_id, vacancy_id)
);


CREATE INDEX IF NOT EXISTS idx_vacancies_type
    ON vacancies(employment_type);

CREATE INDEX IF NOT EXISTS idx_candidates_name
    ON candidates(full_name);

CREATE INDEX IF NOT EXISTS idx_applications_vacancy
    ON applications(vacancy_id);